//! Generate the Rust side of the layout check from the snapshot for this
//! target.
//!
//! For every struct and field the snapshot lists, `measure.rs` holds the
//! `size_of`, `align_of` and `offset_of!` of the same name in
//! `after_effects_sys`. The list comes from the snapshot, so the check covers
//! exactly what the snapshot measured; a name the bindings no longer have
//! fails to compile.

#[allow(dead_code)]
#[path = "src/snapshot.rs"]
mod snapshot;

use std::fmt::Write as _;
use std::path::Path;

use snapshot::{Snapshot, StructSdk};

fn main() {
	println!("cargo::rerun-if-changed=build.rs");
	println!("cargo::rerun-if-changed=src/snapshot.rs");
	println!("cargo::rustc-check-cfg=cfg(sdk_layout_snapshot)");

	let os = std::env::var("CARGO_CFG_TARGET_OS").unwrap();
	let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap();
	let name = format!("{os}-{arch}");
	println!("cargo::rustc-env=SDK_LAYOUT_SNAPSHOT_NAME={name}");
	println!(
		"cargo::rustc-env=SDK_LAYOUT_TARGET={}",
		std::env::var("TARGET").unwrap()
	);

	let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
	let lock = root.join("Cargo.lock");
	println!("cargo::rerun-if-changed={}", lock.display());
	let version = std::fs::read_to_string(&lock)
		.ok()
		.and_then(|text| locked_version(&text, "after-effects-sys"))
		.unwrap_or_default();
	println!("cargo::rustc-env=SDK_LAYOUT_BINDINGS_VERSION={version}");

	let dir = root.join("fixtures").join("sdk-layout");
	println!("cargo::rerun-if-changed={}", dir.display());
	let path = dir.join(format!("{name}.json"));
	let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("measure.rs");
	let Ok(text) = std::fs::read_to_string(&path) else {
		std::fs::write(&out, "").unwrap();
		return;
	};
	println!("cargo::rerun-if-changed={}", path.display());
	let snapshot: Snapshot =
		serde_json::from_str(&text).unwrap_or_else(|e| panic!("{} is not a layout snapshot: {e}", path.display()));
	println!("cargo::rustc-cfg=sdk_layout_snapshot");
	std::fs::write(&out, measure(&snapshot)).unwrap();
}

/// `fn measure() -> Vec<RustStruct>` for every struct in the snapshot.
fn measure(snapshot: &Snapshot) -> String {
	let mut out = String::from("/// Generated by build.rs from the layout snapshot.\n");
	out.push_str("pub(crate) fn measure() -> Vec<RustStruct> {\n\tvec![\n");
	for s in &snapshot.structs {
		let ty = format!("::after_effects_sys::{}", s.rust);
		writeln!(out, "\t\tRustStruct {{").unwrap();
		writeln!(out, "\t\t\trust: {:?},", s.rust).unwrap();
		writeln!(out, "\t\t\tsize: ::core::mem::size_of::<{ty}>(),").unwrap();
		writeln!(out, "\t\t\talign: ::core::mem::align_of::<{ty}>(),").unwrap();
		writeln!(out, "\t\t\tfields: vec![").unwrap();
		let fields = match &s.sdk {
			StructSdk::Found { fields, .. } => fields.as_slice(),
			_ => &[],
		};
		for field in fields {
			let path = &field.rust;
			writeln!(out, "\t\t\t\tfield!({path:?}, {ty}, {path}),").unwrap();
		}
		writeln!(out, "\t\t\t],").unwrap();
		writeln!(out, "\t\t}},").unwrap();
	}
	out.push_str("\t]\n}\n");
	out
}

/// The version of `package` that `Cargo.lock` records.
fn locked_version(lock: &str, package: &str) -> Option<String> {
	let lock = lock.replace("\r\n", "\n");
	let marker = format!("name = \"{package}\"\n");
	let rest = &lock[lock.find(&marker)? + marker.len()..];
	let line = rest.lines().next()?;
	Some(line.strip_prefix("version = \"")?.strip_suffix('"')?.to_string())
}
